/**
 * Discovery helpers shared by the x402 function handlers.
 *
 * The Scaleway/Envoy gateway intercepts the exact path /favicon.ico with its own 404
 * before our function runs, so we cannot serve favicon.ico directly. x402scan
 * (@agentcash/discovery) resolves an icon by first fetching the origin root and parsing
 * <link rel="icon"> from the HTML, and only then probing COMMON_FAVICON_PATHS
 * (/favicon.ico, /favicon.png, /favicon.svg). We satisfy the root-HTML path here and
 * point it at /favicon.png (which, unlike /favicon.ico, does reach the function).
 *
 * The root page doubles as the agent-facing "README": an agent that lands on the origin
 * (curl, MCP client, ERC-8004 shepherd) should learn what the service is, where the
 * machine-readable contracts live, what a call costs, how to pay, and what a 402 means —
 * in one fetch. Every fact on the page is GENERATED by the caller from the same committed
 * constants/files that serve it (spec title/description, `x-payment-info`, endpoint
 * constants), never hand-restated: a restated fact is the next silent drift bug. Surface
 * area is deliberately minimal — human-oriented prose lives on the website, this page is
 * the last mile from discovery to a first (unpaid) honest 402.
 */

/** The fields `buildRootPage` renders; `endpoints` carries absolute hrefs. */
export interface RootPageInput {
  title: string;
  summary: string;
  endpoints: { href: string; label: string }[];
  /** One line per route/price pair, generated from the spec's `x-payment-info`. */
  price: string[];
  payment: string;
  /** The no-wallet first look — usually the curl that returns the honest 402. */
  tryIt: string;
  errors: string;
}

const escapeHtml = (text: string): string =>
  text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** The agent-facing root page. The favicon link stays first — x402scan parses it. */
export function buildRootPage(input: RootPageInput): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<link rel="icon" href="/favicon.png" type="image/jpeg">
<title>${escapeHtml(input.title)}</title>
</head>
<body>
<h1>${escapeHtml(input.title)}</h1>
<p>${escapeHtml(input.summary)}</p>
<h2>Endpoints</h2>
<ul>
${input.endpoints
  .map(
    (e) =>
      `  <li><a href="${escapeHtml(e.href)}">${escapeHtml(e.href)}</a> — ${escapeHtml(e.label)}</li>`,
  )
  .join("\n")}
</ul>
<h2>Price</h2>
<ul>
${input.price.map((p) => `  <li>${escapeHtml(p)}</li>`).join("\n")}
</ul>
<h2>Payment</h2>
<p>${escapeHtml(input.payment)}</p>
<h2>Try it</h2>
<pre>${escapeHtml(input.tryIt)}</pre>
<h2>Errors</h2>
<p>${escapeHtml(input.errors)}</p>
</body>
</html>`;
}
